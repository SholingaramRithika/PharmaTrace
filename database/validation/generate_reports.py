"""Generates docs/CYPHER_QUERIES.md and docs/dataset_validation_report.md from source of truth."""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "database")); sys.path.insert(0, str(ROOT / "database" / "validation"))
from dataset import AS_OF, SCENARIOS, SEED, build_dataset, summary
from reference_rules import evaluate

cat = json.loads((ROOT / "database/queries/catalogue.json").read_text())
L = ["# Cypher Query Catalogue", "",
     f"{len(cat)} parameterized templates ({sum(q['kind']!='write' for q in cat)} read/plan, {sum(q['kind']=='write' for q in cat)} write). "
     "Generated from `database/queries/catalogue.json`, which is the same file the Database Lab API executes.", "",
     "> **Verification status:** parameter declarations, write-guards and input validation are covered by executed offline tests. "
     "Execution of the Cypher itself requires Neo4j and is covered by `backend/tests/test_integration.py`, which has **not yet been run** "
     "(no Neo4j server was available in the authoring sandbox). Run it on your machine and record results in `TESTING.md`.", ""]
for i, q in enumerate(cat, 1):
    L += [f"## Q{i}. {q['title']}", f"`id: {q['id']}` · category: **{q['category']}** · kind: **{q['kind']}** · concept: {q['concept']}", "",
          q["description"], "", "```cypher", q["cypher"], "```", ""]
    if q["params"]:
        L += ["| Parameter | Type | Default | Constraint |", "|---|---|---|---|"]
        for n, r in q["params"].items():
            L.append(f"| `{n}` | {r['type']} | `{r['default']}` | `{r.get('pattern') or r.get('enum') or str(r.get('min'))+'..'+str(r.get('max'))}` |")
        L.append("")
(ROOT / "docs/CYPHER_QUERIES.md").write_text("\n".join(L), encoding="utf-8")

d = build_dataset(); s = summary(d); ev = evaluate(d)
R = ["# Dataset Validation Report", "", "_Generated by `database/validation/generate_reports.py` from the deterministic generator "
     f"(seed {SEED}, reference date {AS_OF}). All data is SYNTHETIC; organizations, medicines and pharmacies are fictional._", "",
     "## Counts produced by the generator", "", "| Node label | Count |", "|---|---:|"]
R += [f"| {k} | {v} |" for k, v in s["nodes"].items()] + [f"| **Total nodes** | **{s['totalNodes']}** |", "", "| Relationship | Count |", "|---|---:|"]
R += [f"| {k} | {v} |" for k, v in s["relationships"].items()] + [f"| **Total relationships** | **{s['totalRelationships']}** |", ""]
roles = {}
for o in d["organizations"]: roles[o["role"]] = roles.get(o["role"], 0) + 1
R += ["Organizations by role: " + ", ".join(f"{k}={v}" for k, v in roles.items()) + ".", "",
      "## Seeded scenarios and what the reference rules detect", "",
      "| # | Scenario | Seeded batch(es) | Rule that must fire |", "|---|---|---|---|"]
rule_for = {"S1_VALID_ROUTE": "none", "S2_UNEXPECTED_DESTINATION": "UNEXPECTED_ROUTE", "S3_UNVERIFIED_SUPPLIER": "UNVERIFIED_SUPPLIER",
            "S4_EXPIRED_BATCH": "EXPIRED_BATCH", "S5_CONFLICTING_IDENTIFIER": "DUPLICATE_LOT", "S6_QUANTITY_INCONSISTENCY": "QUANTITY_MISMATCH",
            "S7_RECALLED_MULTI_DESTINATION": "(recall; no risk rule)", "S8_INCOMPLETE_PATH": "MISSING_EVENT + INCOMPLETE_PATH"}
for i, (k, v) in enumerate(SCENARIOS.items(), 1):
    R.append(f"| {i} | {k} | {', '.join(v)} | {rule_for[k]} |")
R += ["", "## Reference-rule output (pure Python, executed)", "", "```"] + [f"{k:22} {sorted(v)}" for k, v in sorted(ev.items())] + ["```", "",
      "Each rule flags exactly its seeded scenario; the 30 regular batches and `BATCH-VALID-001` raise no findings "
      "(asserted in `backend/tests/test_dataset.py`).", "",
      "## Live-database validation", "",
      "Run `python database/setup_db.py validate` after loading. It compares the live node/relationship counts with the table above. "
      "**Status: not yet executed in the authoring environment (no Neo4j available).**", ""]
(ROOT / "docs/dataset_validation_report.md").write_text("\n".join(R), encoding="utf-8")
print("reports written")
